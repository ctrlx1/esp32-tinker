inline const uint8_t *glyph(char value) {
  const uint8_t code = static_cast<uint8_t>(value);
  if (code < kFirst || code > kLast) {
    return kGlyphs[0];
  }
  return kGlyphs[code - kFirst];
}

inline uint16_t textWidth(const char *text) {
  if (!text || !text[0]) {
    return 0;
  }
  uint16_t count = 0;
  while (text[count]) {
    ++count;
  }
  return static_cast<uint16_t>(count * kWidth + (count - 1));
}

